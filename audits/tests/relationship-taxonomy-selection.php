<?php
/**
 * Integration checks for snippet 330 using WordPress Core and disposable fixtures.
 * Run both commands against an installed, local WordPress at http://snippet-330.test.
 * php audits/tests/relationship-taxonomy-selection.php /path/to/wp-load.php
 * php audits/tests/relationship-taxonomy-selection.php /path/to/wp-load.php empty
 */
if ( PHP_SAPI !== 'cli' || ! isset( $argv[1] ) || ! is_file( $argv[1] ) ) {
    throw new RuntimeException( 'Usage: php ' . basename( __FILE__ ) . ' /path/to/wp-load.php [empty]' );
}
define( 'ABSPATH', dirname( $argv[1] ) . '/' );
$_SERVER['HTTP_HOST'] = 'snippet-330.test';
require $argv[1];
if ( wp_get_environment_type() !== 'local' || home_url() !== 'http://snippet-330.test' ) {
    throw new RuntimeException( 'Use an isolated local installation at http://snippet-330.test.' );
}
require dirname( __DIR__, 2 ) . '/wordpress/snippets/php/330-relationship-taxonomy-loop.php';

function expect_same( $expected, $actual, $message ) {
    if ( $expected !== $actual ) {
        throw new RuntimeException( $message . ': expected ' . wp_json_encode( $expected ) . ', got ' . wp_json_encode( $actual ) );
    }
    echo "PASS " . $message . PHP_EOL;
}

function fixture_term( $taxonomy, $name, $parent = 0 ) {
    $term = wp_insert_term( $name, $taxonomy, [ 'parent' => $parent ] );
    if ( is_wp_error( $term ) ) {
        throw new RuntimeException( $term->get_error_message() );
    }
    return (int) $term['term_id'];
}

function loop_args( $id, $args = [], $setting = 'term_taxonomy_id' ) {
    return apply_filters( 'elementor/loop_taxonomy/args', $args + [ 'taxonomy' => 'locatie' ], [ $setting => $id ], [] );
}

function loop_ids( $id, $args = [], $setting = 'term_taxonomy_id' ) {
    $query = loop_args( $id, $args + [ 'fields' => 'ids', 'orderby' => 'term_id' ], $setting );
    $ids = get_terms( $query );
    if ( is_wp_error( $ids ) ) {
        throw new RuntimeException( $ids->get_error_message() );
    }
    return array_map( 'intval', $ids );
}

class FixtureLoopWidget {
    private $name;
    public $mode = 'show_all';
    public function get_settings( $key ) { return $key === 'post_taxonomy_query_filter_by' ? $this->mode : null; }

    public function __construct( $name ) { $this->name = $name; }
    public function get_name() { return $this->name; }
}

global $wpdb;
$wpdb->query( 'START TRANSACTION' );
try {
    register_post_type( 'vacature', [ 'public' => true ] );
    register_taxonomy( 'locatie', 'vacature', [ 'hierarchical' => true, 'public' => true ] );
    register_taxonomy( 'vakgebied', 'vacature', [ 'public' => true ] );
    register_taxonomy( 'vac_status', 'vacature', [ 'public' => true ] );
    $open = fixture_term( 'vac_status', 'Open' );
    $closed = fixture_term( 'vac_status', 'Vervuld' );
    $nl = fixture_term( 'locatie', 'Nederland' );
    $nh = fixture_term( 'locatie', 'Noord-Holland', $nl );
    $ut = fixture_term( 'locatie', 'Utrecht', $nl );
    $ams = fixture_term( 'locatie', 'Amsterdam', $nh );
    $amf = fixture_term( 'locatie', 'Amersfoort', $ut );
    $edam = fixture_term( 'locatie', 'Edam', $nh );
    $field = fixture_term( 'vakgebied', 'Mechanisch' );
    $page = wp_insert_post( [ 'post_type' => 'page', 'post_title' => 'Locaties', 'post_status' => 'publish' ] );
    $GLOBALS['wp_query'] = new WP_Query( [ 'page_id' => $page ] );

    $empty = ( $argv[2] ?? '' ) === 'empty';
    foreach ( [ $ams, $amf, $edam ] as $city ) {
        $vacancy = wp_insert_post( [ 'post_type' => 'vacature', 'post_title' => 'Fixture ' . $city, 'post_status' => 'publish' ] );
        wp_set_object_terms( $vacancy, [ $city ], 'locatie' );
        wp_set_object_terms( $vacancy, [ $field ], 'vakgebied' );
        wp_set_object_terms( $vacancy, [ $empty || $city === $edam ? $closed : $open ], 'vac_status' );
    }

    $manual = 'relationship_level_2_manual';
    $legacy = 'relationship_level_2';
    if ( $empty ) {
        expect_same( [], loop_ids( $manual, [ 'include' => [ $ams ] ] ), 'no open vacancies produces no cards' );
        // Older Core releases treat include=[0] differently. Compare the legacy result
        // with the native query generated by v5.5 on the running WordPress version.
        $previous = get_terms( [ 'taxonomy' => 'locatie', 'include' => [ 0 ], 'fields' => 'ids', 'orderby' => 'term_id' ] );
        expect_same( array_map( 'intval', $previous ), loop_ids( $legacy ), 'legacy empty-vacancy query matches v5.5' );
        return;
    }

    $native = get_term_link( $ams, 'locatie' );
    $native_amf = get_term_link( $amf, 'locatie' );
    $combo = home_url( '/vacatures/locatie/nederland/noord-holland/amsterdam/' );
    $grid = new FixtureLoopWidget( 'loop-grid' );
    $carousel = new FixtureLoopWidget( 'loop-carousel' );
    $before = 'elementor/frontend/widget/before_render';
    $after = 'elementor/frontend/widget/after_render';

    expect_same( [ $ams, $amf ], loop_ids( $manual ), 'unrestricted manual city query' );
    expect_same( [ $amf ], loop_ids( $manual, [ 'exclude' => [ $ams ] ] ), 'exclude Amsterdam' );
    expect_same( [ $ams ], loop_ids( $manual, [ 'include' => "$ams,$amf", 'exclude' => (string) $amf ] ), 'CSV selection and exclusion precedence' );
    expect_same( [], loop_ids( $manual, [ 'include' => [ $ams ], 'exclude' => [ $ams ] ] ), 'excluded final card stays empty' );
    expect_same( [], loop_ids( $manual, [ 'include' => [ $edam, $nh ] ] ), 'closed vacancies and the wrong depth are ineligible' );
    expect_same( [ $amf ], loop_ids( $manual, [ 'exclude_tree' => [ $nh ] ] ), 'exclude_tree removes descendant cities' );
    expect_same( [ $amf, $ams ], loop_ids( $manual, [ 'include' => [ $amf, $ams ], 'orderby' => 'include' ] ), 'native include order' );
    expect_same( [ $amf ], loop_ids( $manual, [ 'number' => 1, 'offset' => 1 ] ), 'pagination follows the filtered selection' );
    $exclude_amsterdam = static function ( $args ) use ( $ams ) {
        $args['exclude'] = [ $ams ];
        return $args;
    };
    add_filter( 'elementor/loop_taxonomy/args', $exclude_amsterdam, 20 );
    expect_same( [ $amf ], loop_ids( $manual ), 'earlier query filters are respected' );
    remove_filter( 'elementor/loop_taxonomy/args', $exclude_amsterdam, 20 );
    expect_same( [ $field ], loop_ids( 'relationship_level_0_manual', [ 'taxonomy' => 'vakgebied' ] ), 'flat taxonomy level zero' );
    expect_same( [], loop_ids( 'relationship_level_1_manual', [ 'taxonomy' => 'vakgebied' ] ), 'flat taxonomy deeper level' );
    expect_same( [ $nh, $ut ], loop_ids( 'relationship_level_1_manual' ), 'inferred provinces of open vacancies' );
    expect_same( $native, get_term_link( $ams, 'locatie' ), 'query outside a widget does not rewrite links' );

    do_action( $before, $grid );
    do_action( $after, $grid );
    $grid->mode = 'manual_selection';
    do_action( $before, $grid );
    expect_same( [ $ams ], loop_ids( $legacy, [ 'include' => [ $ams ] ] ), 'standard ID follows Elementor manual include' );
    expect_same( [ $amf ], loop_ids( $legacy, [ 'exclude' => [ $ams ] ] ), 'standard ID follows Elementor manual exclude' );
    do_action( $after, $grid );
    $grid->mode = 'show_all';
    do_action( $before, $grid );
    $amsterdam_args = [ 'include' => [ $ams ], 'term_taxonomy_id' => $manual ];
    expect_same( [ $ams ], loop_ids( $manual, $amsterdam_args, 'post_taxonomy_term_taxonomy_id' ), 'include Amsterdam using the prefixed Query ID setting' );
    $queries_before_repeat = $wpdb->num_queries;
    loop_ids( $manual, $amsterdam_args, 'post_taxonomy_term_taxonomy_id' );
    expect_same( $queries_before_repeat, $wpdb->num_queries, 'identical warm selection makes no additional SQL queries' );
    expect_same( $combo, get_term_link( $ams, 'locatie' ), 'selected card has the full combo link' );
    expect_same( $native_amf, get_term_link( $amf, 'locatie' ), 'unselected term link is native' );
    $GLOBALS['tfsc_force_native_term_link'] = true;
    expect_same( $native, get_term_link( $ams, 'locatie' ), 'explicit native-link override' );
    unset( $GLOBALS['tfsc_force_native_term_link'] );
    do_action( $before, $carousel );
    $other = [ 'taxonomy' => 'locatie', 'include' => [ $ams ] ];
    expect_same( $other, loop_args( 'unrelated_query', $other ), 'unrelated Query ID keeps the complete native query' );
    expect_same( $native, get_term_link( $ams, 'locatie' ), 'nested native loop gets independent links' );
    do_action( $after, $carousel );
    expect_same( $combo, get_term_link( $ams, 'locatie' ), 'outer manual link restored after nested loop' );
    expect_same( [], loop_ids( $manual, [ 'include' => [ $edam ] ] ), 'repeat query in the same widget can become empty' );
    expect_same( $native, get_term_link( $ams, 'locatie' ), 'empty repeat query drops the previous card link' );
    expect_same( [ $ams ], loop_ids( $manual, $amsterdam_args ), 'repeat query can restore an eligible Amsterdam card' );
    expect_same( $combo, get_term_link( $ams, 'locatie' ), 'restored card has its combo link' );
    do_action( $after, $grid );
    expect_same( $native, get_term_link( $ams, 'locatie' ), 'later same-taxonomy links remain native' );

    do_action( $before, $grid );
    expect_same( [ $ams, $amf ], loop_ids( $legacy, [ 'include' => [ $ams ], 'exclude' => [ $amf ] ] ), 'legacy ID retains its own eligibility list' );
    do_action( $after, $grid );
    expect_same( $combo, get_term_link( $ams, 'locatie' ), 'legacy term-link behavior survives its render scope' );
    unregister_taxonomy( 'vac_status' );
    expect_same( [], loop_ids( $manual ), 'missing status taxonomy fails closed in the manual variant' );
} finally {
    $wpdb->query( 'ROLLBACK' );
}
